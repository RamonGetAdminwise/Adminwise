import { writeFileSync } from "node:fs";
import path from "node:path";
import ExcelJS from "exceljs";

/**
 * Writes the Nordpart price list fixture (invented company, invented items):
 *   fixtures/nordpart/price-list.xlsx   the file "as the customer keeps it"
 *   fixtures/nordpart/price-list.json   the 120 items a correct import must find
 *
 * The sheet is deliberately not tidy, like real ones: a title block above the
 * header, Polish column titles, group headings between items, a gross price
 * column next to the net one, one item priced "na zapytanie" (on request) and
 * one repeated code. Run with: pnpm tsx scripts/make-price-list-fixture.ts
 */

interface Item {
  code: string;
  name: string;
  unit: string;
  netPriceCents: number;
  aliases: string[];
}

const GROUPS: { title: string; prefix: string; name: (size: number) => string; alias: (size: number) => string; unit: string; base: number; step: number; sizes: number[] }[] = [
  { title: "Pompy hydrauliczne", prefix: "PZ", name: (s) => `Pompa hydrauliczna zębata PZ-${s}`, alias: (s) => `hydraulic gear pump PZ-${s}`, unit: "szt.", base: 84000, step: 2150, sizes: [10, 16, 20, 25, 32, 40, 50, 63, 80, 100, 125, 160, 200, 250, 315] },
  { title: "Motoreduktory", prefix: "GM", name: (s) => `Motoreduktor walcowy GM-${s}`, alias: (s) => `gear motor GM-${s}`, unit: "szt.", base: 129000, step: 3475, sizes: [15, 20, 25, 30, 40, 50, 60, 75, 90, 110, 130, 150, 180, 220, 300] },
  { title: "Uszczelki i pierścienie", prefix: "U", name: (s) => `Uszczelka gumowa U-${s}`, alias: (s) => `rubber seal U-${s}`, unit: "szt.", base: 320, step: 45, sizes: [8, 10, 12, 14, 16, 18, 20, 22, 25, 28, 30, 35, 40, 45, 50] },
  { title: "Łożyska kulkowe", prefix: "LK", name: (s) => `Łożysko kulkowe LK-${s}`, alias: (s) => `ball bearing LK-${s}`, unit: "szt.", base: 1890, step: 136, sizes: [6000, 6001, 6002, 6003, 6004, 6005, 6006, 6007, 6008, 6009, 6010, 6200, 6201, 6202, 6203] },
  { title: "Węże hydrauliczne", prefix: "WH", name: (s) => `Wąż hydrauliczny DN${s} 2SN`, alias: (s) => `hydraulic hose DN${s}`, unit: "mb", base: 2450, step: 310, sizes: [6, 8, 10, 12, 16, 19, 25, 31, 38, 51, 60, 63, 76, 89, 102] },
  { title: "Filtry", prefix: "FO", name: (s) => `Filtr oleju FO-${s}`, alias: (s) => `oil filter FO-${s}`, unit: "szt.", base: 4680, step: 255, sizes: [100, 110, 120, 130, 140, 150, 160, 170, 180, 190, 200, 210, 220, 230, 240] },
  { title: "Zawory", prefix: "ZK", name: (s) => `Zawór kulowy ZK-${s}`, alias: (s) => `ball valve ZK-${s}`, unit: "szt.", base: 6120, step: 890, sizes: [4, 6, 8, 10, 13, 15, 20, 25, 32, 40, 50, 65, 80, 100, 125] },
  { title: "Sprzęgła", prefix: "SP", name: (s) => `Sprzęgło kłowe SP-${s}`, alias: (s) => `jaw coupling SP-${s}`, unit: "kpl.", base: 9870, step: 1240, sizes: [14, 19, 24, 28, 38, 42, 48, 55, 65, 75, 90, 100, 110, 125, 140] },
];

const items: Item[] = [];
const sheetRows: (string | number | null)[][] = [];
for (const group of GROUPS) {
  sheetRows.push([null, group.title, null, null, null, null]);
  group.sizes.forEach((size, i) => {
    const item: Item = {
      code: `${group.prefix}-${size}`,
      name: group.name(size),
      unit: group.unit,
      netPriceCents: group.base + group.step * i * (i + 3),
      aliases: [group.alias(size)],
    };
    items.push(item);
    const net = item.netPriceCents / 100;
    sheetRows.push([item.code, item.name, item.unit, net, Math.round(item.netPriceCents * 1.23) / 100, item.aliases.join("; ")]);
  });
}
// Two rows a careful import must leave out and report.
sheetRows.push([null, "Pozostałe", null, null, null, null]);
sheetRows.push(["AG-01", "Agregat hydrauliczny na zamówienie", "szt.", "na zapytanie", null, "hydraulic power unit"]);
sheetRows.push(["PZ-40", "Pompa PZ-40 (stary indeks)", "szt.", 1999, 2458.77, null]);

const workbook = new ExcelJS.Workbook();
const sheet = workbook.addWorksheet("Cennik 2026");
sheet.addRow(["Nordpart sp. z o.o. - cennik części i podzespołów"]);
sheet.addRow(["Ceny netto w PLN, ważne od 1 września 2026"]);
sheet.addRow([]);
sheet.addRow(["Indeks", "Nazwa towaru", "J.m.", "Cena netto PLN", "Cena brutto PLN", "Inne nazwy"]);
for (const row of sheetRows) sheet.addRow(row);
sheet.getColumn(2).width = 44;
sheet.getColumn(6).width = 32;

const dir = path.resolve(import.meta.dirname, "../fixtures/nordpart");
await workbook.xlsx.writeFile(path.join(dir, "price-list.xlsx"));
writeFileSync(
  path.join(dir, "price-list.json"),
  JSON.stringify(
    {
      _comment: "The items a correct import of price-list.xlsx finds, and the two rows it must report. Generated by scripts/make-price-list-fixture.ts.",
      currency: "PLN",
      headerRow: 4,
      items,
      skipped: [
        { row: 4 + sheetRows.length - 1, reason: "price_not_readable" },
        { row: 4 + sheetRows.length, reason: "duplicate_code" },
      ],
    },
    null,
    2,
  ) + "\n",
);
console.log(`Wrote ${items.length} items to fixtures/nordpart/price-list.xlsx and price-list.json`);
